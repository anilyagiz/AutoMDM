func TestIntegrationsGitops(t *testing.T) {
	testingSuite := new(integrationGitopsTestSuite)
	testingSuite.WithServer.Suite = &testingSuite.Suite
	suite.Run(t, testingSuite)
}

type integrationGitopsTestSuite struct {
	suite.Suite
	integrationtest.WithServer
	automdmCfg config.AutoMDMConfig
}

func (s *integrationGitopsTestSuite) SetupSuite() {
	s.WithDS.SetupSuite("integrationGitopsTestSuite")

	appConf, err := s.DS.AppConfig(context.Background())
	require.NoError(s.T(), err)
	appConf.MDM.EnabledAndConfigured = true
	appConf.MDM.AppleBMEnabledAndConfigured = true
	appConf.MDM.WindowsEnabledAndConfigured = true
	err = s.DS.SaveAppConfig(context.Background(), appConf)
	require.NoError(s.T(), err)

	testCert, testKey, err := appleMdm.NewSCEPCACertKey()
	require.NoError(s.T(), err)
	testCertPEM := tokenpki.PEMCertificate(testCert.Raw)
	testKeyPEM := tokenpki.PEMRSAPrivateKey(testKey)

	automdmCfg := config.TestConfig()
	config.SetTestMDMConfig(s.T(), &automdmCfg, testCertPEM, testKeyPEM, "../../../../server/service/testdata")
	automdmCfg.Osquery.EnrollCooldown = 0

	mdmStorage, err := s.DS.NewMDMAppleMDMStorage()
	require.NoError(s.T(), err)
	depStorage, err := s.DS.NewMDMAppleDEPStorage()
	require.NoError(s.T(), err)
	scepStorage, err := s.DS.NewSCEPDepot()
	require.NoError(s.T(), err)
	redisPool := redistest.SetupRedis(s.T(), "zz", false, false, false)

	serverConfig := service.TestServerOpts{
		License: &automdm.LicenseInfo{
			Tier: automdm.TierFree,
		},
		AutoMDMConfig: &automdmCfg,
		MDMStorage:    mdmStorage,
		DEPStorage:    depStorage,
		SCEPStorage:   scepStorage,
		Pool:          redisPool,
		APNSTopic:     "com.apple.mgmt.External.10ac3ce5-4668-4e58-b69a-b2b5ce667589",
	}
	err = s.DS.InsertMDMConfigAssets(context.Background(), []automdm.MDMConfigAsset{
		{Name: automdm.MDMAssetSCEPChallenge, Value: []byte("scepchallenge")},
	}, nil)
	require.NoError(s.T(), err)
	users, server := svctest.RunServerForTestsWithDS(s.T(), s.DS, &serverConfig)
	s.T().Setenv("AUTOMDM_SERVER_ADDRESS", server.URL) // automdmctl always uses this env var in tests
	s.Server = server
	s.Users = users
	s.automdmCfg = automdmCfg

	appConf, err = s.DS.AppConfig(context.Background())
	require.NoError(s.T(), err)
	appConf.ServerSettings.ServerURL = server.URL
	// Disable gitops exceptions so that existing tests can freely use labels, secrets, etc. in their YAML.
	appConf.GitOpsConfig.Exceptions = automdm.GitOpsExceptions{}
	err = s.DS.SaveAppConfig(context.Background(), appConf)
	require.NoError(s.T(), err)
}

func (s *integrationGitopsTestSuite) TearDownSuite() {
	appConf, err := s.DS.AppConfig(context.Background())
	require.NoError(s.T(), err)
	appConf.MDM.EnabledAndConfigured = false
	err = s.DS.SaveAppConfig(context.Background(), appConf)
	require.NoError(s.T(), err)
}

// TestAutoMDMGitops runs `automdmctl gitops` on the global config scaffold generated by `automdmctl new`,
// validating the starter files customers actually get.
func (s *integrationGitopsTestSuite) TestAutoMDMGitops() {
	t := s.T()

	automdmctlConfig := s.createAutoMDMctlConfig()

	// Generate the starter GitOps files
	repoDir := path.Join(t.TempDir(), "it-and-security")
	_ = automdmctltest.RunAppForTest(t, []string{"new", "--org-name", "Fleet Device Management", "--dir", repoDir})

	// Set the required environment variables
	t.Setenv("AUTOMDM_URL", s.Server.URL)
	globalFile := path.Join(repoDir, "default.yml")

	// Dry run
	_ = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile, "--dry-run"})

	// Real run
	_ = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile})
}

func (s *integrationGitopsTestSuite) createAutoMDMctlConfig() *os.File {
	t := s.T()
	// Create a temporary automdmctl config file
	automdmctlConfig, err := os.CreateTemp(t.TempDir(), "*.yml")
	require.NoError(t, err)
	// GitOps user is a premium feature, so we simply use an admin user.
	token := s.GetTestToken("admin1@example.com", test.GoodPassword)
	configStr := fmt.Sprintf(
		`
contexts:
  default:
    address: %s
    tls-skip-verify: true
    token: %s
`, s.Server.URL, token,
	)
	_, err = automdmctlConfig.WriteString(configStr)
	require.NoError(t, err)
	return automdmctlConfig
}

func (s *integrationGitopsTestSuite) TestAutoMDMGitopsWithAutoMDMSecrets() {
	t := s.T()
	const (
		secretName1 = "NAME"
		secretName2 = "LENGTH"
	)
	ctx := context.Background()
	automdmctlConfig := s.createAutoMDMctlConfig()

	// Set the required environment variables
	t.Setenv("AUTOMDM_URL", s.Server.URL)
	t.Setenv("AUTOMDM_GLOBAL_ENROLL_SECRET", "global_enroll_secret")
	t.Setenv("AUTOMDM_SECRET_"+secretName1, "secret_value")
	t.Setenv("AUTOMDM_SECRET_"+secretName2, "2")
	globalFile := path.Join("..", "..", "automdmctl", "testdata", "gitops", "global_integration.yml")

	// Dry run
	_ = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile, "--dry-run"})
	secrets, err := s.DS.GetSecretVariables(ctx, []string{secretName1})
	require.NoError(t, err)
	require.Empty(t, secrets)

	// Real run
	_ = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile})
	// Check secrets
	secrets, err = s.DS.GetSecretVariables(ctx, []string{secretName1, secretName2})
	require.NoError(t, err)
	require.Len(t, secrets, 2)
	for _, secret := range secrets {
		switch secret.Name {
		case secretName1:
			assert.Equal(t, "secret_value", secret.Value)
		case secretName2:
			assert.Equal(t, "2", secret.Value)
		default:
			t.Fatalf("unexpected secret %s", secret.Name)
		}
	}

	// Check script(s)
	scriptID, err := s.DS.GetScriptIDByName(ctx, "automdm-secret.sh", nil)
	require.NoError(t, err)
	expected, err := os.ReadFile("../../automdmctl/testdata/gitops/lib/automdm-secret.sh")
	require.NoError(t, err)
	script, err := s.DS.GetScriptContents(ctx, scriptID)
	require.NoError(t, err)
	assert.Equal(t, expected, script)

	// Check Apple profiles
	profiles, err := s.DS.ListMDMAppleConfigProfiles(ctx, nil)
	require.NoError(t, err)
	require.Len(t, profiles, 1)
	assert.Contains(t, string(profiles[0].Mobileconfig), "$AUTOMDM_SECRET_"+secretName1)
	// Check Windows profiles
	allProfiles, _, err := s.DS.ListMDMConfigProfiles(ctx, nil, automdm.ListOptions{})
	require.NoError(t, err)
	require.Len(t, allProfiles, 2)
	var windowsProfileUUID string
	for _, profile := range allProfiles {
		if profile.Platform == "windows" {
			windowsProfileUUID = profile.ProfileUUID
		}
	}
	require.NotEmpty(t, windowsProfileUUID)
	winProfile, err := s.DS.GetMDMWindowsConfigProfile(ctx, windowsProfileUUID)
	require.NoError(t, err)
	assert.Contains(t, string(winProfile.SyncML), "${AUTOMDM_SECRET_"+secretName2+"}")
}

func (s *integrationGitopsTestSuite) TestAutoMDMGitopsDDMAutoMDMVarsRequiresPremium() {
	t := s.T()
	automdmctlConfig := s.createAutoMDMctlConfig()

	// Create a DDM declaration with an AutoMDM variable
	declDir := t.TempDir()
	declFile := path.Join(declDir, "decl-automdmvar.json")
	err := os.WriteFile(declFile, []byte(`{
		"Type": "com.apple.configuration.management.test",
		"Identifier": "com.example.automdmvar-test",
		"Payload": {"Value": "$AUTOMDM_VAR_HOST_HARDWARE_SERIAL"}
	}`), 0o644)
	require.NoError(t, err)

	globalFile, err := os.CreateTemp(t.TempDir(), "*.yml")
	require.NoError(t, err)
	_, err = globalFile.WriteString(fmt.Sprintf(`
agent_options:
controls:
  apple_settings:
    configuration_profiles:
      - path: %s
org_settings:
  server_settings:
    server_url: $AUTOMDM_URL
  org_info:
    org_name: AutoMDM
  secrets:
policies:
queries:
`, declFile))
	require.NoError(t, err)

	t.Setenv("AUTOMDM_URL", s.Server.URL)

	// Applying a DDM declaration with AutoMDM variables should fail without a premium license
	_, err = automdmctltest.RunAppNoChecks([]string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile.Name()})
	require.ErrorContains(t, err, "missing or invalid license")
}

// customHostVitalsGlobalYAML writes a minimal global GitOps file with the
// given `custom_host_vitals:` body (e.g. "- name: Foo\n- name: Bar", or ""
// to omit the key entirely, which is the declarative clear-all case).
func (s *integrationGitopsTestSuite) customHostVitalsGlobalYAML(customHostVitalsBody string) string {
	t := s.T()
	f, err := os.CreateTemp(t.TempDir(), "*.yml")
	require.NoError(t, err)
	customHostVitalsKey := ""
	if customHostVitalsBody != "" {
		customHostVitalsKey = "custom_host_vitals:\n" + customHostVitalsBody
	}
	_, err = f.WriteString(fmt.Sprintf(`
policies:
queries:
agent_options:
controls:
org_settings:
  server_settings:
    server_url: $AUTOMDM_URL
  org_info:
    org_name: AutoMDM
  secrets:
%s
`, customHostVitalsKey))
	require.NoError(t, err)
	return f.Name()
}

func (s *integrationGitopsTestSuite) TestAutoMDMGitopsCustomHostVitals() {
	t := s.T()
	ctx := t.Context()
	automdmctlConfig := s.createAutoMDMctlConfig()
	t.Setenv("AUTOMDM_URL", s.Server.URL)

	listVitals := func() []automdm.CustomHostVital {
		vitals, _, _, err := s.DS.ListCustomHostVitals(ctx, automdm.ListOptions{})
		require.NoError(t, err)
		return vitals
	}
	names := func(vitals []automdm.CustomHostVital) []string {
		out := make([]string, 0, len(vitals))
		for _, v := range vitals {
			out = append(out, v.Name)
		}
		return out
	}

	// Ensure a clean slate: this is global state shared across the suite's tests.
	defer func() {
		globalFile := s.customHostVitalsGlobalYAML("")
		automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile})
		require.Empty(t, listVitals())
	}()

	// Dry run validates without persisting, and logs what would've been created.
	globalFileV1 := s.customHostVitalsGlobalYAML("  - name: Asset tag\n  - name: Department\n")
	out := automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileV1, "--dry-run"})
	assert.Contains(t, out, "[+] would've created 2 custom host vitals")
	assert.Contains(t, out, "gitops dry run succeeded")
	assert.Empty(t, listVitals())

	// Real run creates both, and logs what it created.
	out = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileV1})
	assert.Contains(t, out, "[+] creating 2 custom host vitals")
	assert.Contains(t, out, "gitops succeeded")
	require.ElementsMatch(t, []string{"Asset tag", "Department"}, names(listVitals()))

	byName := make(map[string]uint)
	for _, v := range listVitals() {
		byName[v.Name] = v.ID
	}
	assetTagID := byName["Asset tag"]

	// Re-applying with "Department" dropped and "Role" added: Department is
	// deleted, Role is created, Asset tag is retained with the same ID.
	globalFileV2 := s.customHostVitalsGlobalYAML("  - name: Asset tag\n  - name: Role\n")
	out = automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileV2})
	assert.Contains(t, out, "[-] deleting custom host vital 'Department'")
	assert.Contains(t, out, "[+] creating 1 custom host vital")
	require.ElementsMatch(t, []string{"Asset tag", "Role"}, names(listVitals()))
	for _, v := range listVitals() {
		if v.Name == "Asset tag" {
			require.Equal(t, assetTagID, v.ID)
		}
	}

	// A dry run still sends the request to the server (with DryRun set), so
	// server-side validation -- like the collation-aware duplicate-name check,
	// which is not enforced by the local diff -- is still exercised without
	// persisting.
	globalFileDupe := s.customHostVitalsGlobalYAML("  - name: Asset tag\n  - name: asset tag\n")
	_, err := automdmctltest.RunAppNoChecks([]string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileDupe, "--dry-run"})
	require.ErrorContains(t, err, "duplicate custom host vital names")
	require.ElementsMatch(t, []string{"Asset tag", "Role"}, names(listVitals()))

	// A script referencing $AUTOMDM_HOST_VITAL_<id> for "Asset tag" blocks its
	// removal: applying a config that drops it from custom_host_vitals errors
	// the whole run, and no vitals are removed.
	script, err := s.DS.NewScript(ctx, &automdm.Script{
		Name:           "collect-asset-tag.sh",
		ScriptContents: fmt.Sprintf("echo $%s%d", automdm.CustomHostVitalPrefix, assetTagID),
	})
	require.NoError(t, err)

	globalFileV3 := s.customHostVitalsGlobalYAML("  - name: Role\n")
	_, err = automdmctltest.RunAppNoChecks([]string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileV3})
	require.ErrorContains(t, err, "Couldn't delete")
	require.ErrorContains(t, err, "Asset tag")
	require.ElementsMatch(t, []string{"Asset tag", "Role"}, names(listVitals()))

	require.NoError(t, s.DS.DeleteScript(ctx, script.ID))

	// With the reference gone, the same config now succeeds.
	automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileV3})
	require.ElementsMatch(t, []string{"Role"}, names(listVitals()))

	// An absent `custom_host_vitals:` key is a declarative clear-all.
	globalFileAbsent := s.customHostVitalsGlobalYAML("")
	automdmctltest.RunAppForTest(t, []string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFileAbsent})
	require.Empty(t, listVitals())
}

func (s *integrationGitopsTestSuite) TestAutoMDMGitopsPatchDeadlineSettingsFree() {
	t := s.T()
	ctx := t.Context()
	automdmctlConfig := s.createAutoMDMctlConfig()
	t.Setenv("AUTOMDM_URL", s.Server.URL)

	dir := t.TempDir()
	globalFile := path.Join(dir, "global.yml")
	require.NoError(t, os.WriteFile(globalFile, []byte(`
agent_options:
controls:
org_settings:
  server_settings:
    server_url: $AUTOMDM_URL
  org_info:
    org_name: AutoMDM
  secrets:
policies:
reports:
`), 0o644))
	unassignedFile := path.Join(dir, "unassigned.yml")
	require.NoError(t, os.WriteFile(unassignedFile, []byte(`name: Unassigned
controls:
policies:
software:
  patch_deadline_settings:
    days: [monday]
    time: "09:30"
`), 0o644))

	out, err := automdmctltest.RunAppNoChecks([]string{"gitops", "--config", automdmctlConfig.Name(), "-f", globalFile, "-f", unassignedFile})
	require.NoError(t, err)
	require.Contains(t, out.String(), "skipping automdm config")
	require.NotContains(t, out.String(), "patch deadline settings")
	got, err := s.DS.GetPatchDeadlineSettings(ctx, 0)
	require.NoError(t, err)
	require.Equal(t, automdm.DefaultPatchDeadlineSettings(0), got)
}
